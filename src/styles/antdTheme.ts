import { theme, type MappingAlgorithm, type ThemeConfig } from 'antd';
import { fontFamily, palettes, shape, type Palette, type ThemeName } from './tokens';

// Ant Design's own algorithms re-mix the base colours (in dark mode the accent,
// danger, ok and warn it derives are dimmer than the ones given, which drops
// their text below 4.5:1). This keeps the algorithm for everything else and
// puts the exact tokens.ts colours back.
const exactColours = (base: MappingAlgorithm, c: Palette): MappingAlgorithm => (seed, mapToken) => ({
  ...base(seed, mapToken),
  colorPrimary: c.accent,
  colorInfo: c.accent,
  colorLink: c.accent,
  colorSuccess: c.ok,
  colorWarning: c.warn,
  colorError: c.danger,
});

// Ant Design reads its colours as plain values, so the theme is built from the
// same tokens.ts values the CSS variables come from.
